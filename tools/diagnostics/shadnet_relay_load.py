#!/usr/bin/env python3
"""Privacy-safe measurement of *actual* shadNet game payload forwarded via UDP.

Consumes lines generated by pinned ServerLink::Hub::Tick:
  server link: <private account> in N frames/B bytes, out N frames/B bytes, N pings
No online IDs, addresses, account names or raw log lines are printed.
The counts cover *game relay payload only* and exclude packet/UDP overhead,
team world messages, Qt CPU/RAM and external retransmissions.
A real, measured elapsed test duration must be supplied for rates. Repeated
logs, incomplete windows and rotated files can bias results.
"""
from __future__ import annotations
import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re
import sys

# Greedily skip potentially sensitive account identifiers and addresses.
STAT = re.compile(
    r"\bserver link: .* in ([0-9]{1,20}) frames/([0-9]{1,20}) bytes, "
    r"out ([0-9]{1,20}) frames/([0-9]{1,20}) bytes, ([0-9]{1,20}) pings(?:\b|$)"
)
MAX_COUNTER = 2**64 - 1

@dataclass
class Counters:
    samples: int = 0
    frames_in: int = 0
    bytes_in: int = 0
    frames_out: int = 0
    bytes_out: int = 0
    pings: int = 0

    def add(self, groups: tuple[str, ...]) -> None:
        values = [int(v) for v in groups]
        if any(v > MAX_COUNTER for v in values):
            raise ValueError("unexpected wider-than-64-bit relay counter")
        self.samples += 1
        self.frames_in += values[0]
        self.bytes_in += values[1]
        self.frames_out += values[2]
        self.bytes_out += values[3]
        self.pings += values[4]

    def summary(self, *, duration_seconds: float | None = None) -> dict:
        result = {
            "source": "real shadNet ServerLink::Hub::Tick relay log counters",
            "sampled_link_windows": self.samples,
            "relay_game_frames_in": self.frames_in,
            "relay_game_payload_bytes_in": self.bytes_in,
            "relay_game_frames_out": self.frames_out,
            "relay_game_payload_bytes_out": self.bytes_out,
            "lobby_and_world_control_bytes_included": False,
            "ip_udp_headers_and_resent_packets_included": False,
            "cpu_ram_and_direct_p2p_measured": False,
            "personal_identifiers_in_output": False,
            "release_ready": False,
        }
        if duration_seconds is not None:
            if not (duration_seconds > 0 and duration_seconds <= 31_536_000):
                raise ValueError("duration_seconds must be within 0..one year")
            result["supplied_measured_duration_seconds"] = duration_seconds
            result["relay_payload_ingress_mbps_approx"] = round(
                self.bytes_in * 8 / duration_seconds / 1_000_000, 6)
            result["relay_payload_egress_mbps_approx"] = round(
                self.bytes_out * 8 / duration_seconds / 1_000_000, 6)
            result["rate_caveat"] = (
                "Approximate: log stats are flushed in windows and may not "
                "cover the entire user-supplied duration."
            )
        return result


def parse(lines, *, max_lines: int = 2_000_000) -> Counters:
    counts = Counters()
    for index, line in enumerate(lines):
        if index >= max_lines:
            raise ValueError("relay log exceeds bounded input; choose a shorter fixture")
        m = STAT.search(line)
        if m:
            counts.add(m.groups())
    return counts


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("log", type=Path, help="PRIVATE local shadnet log file; never upload it publicly")
    ap.add_argument("--measured-duration-sec", type=float,
                    help="elapsed stopwatch time from an instrumented live game test")
    args = ap.parse_args()
    try:
        if not args.log.is_file() or args.log.stat().st_size > 250_000_000:
            raise ValueError("missing or oversized relay log")
        with args.log.open("r", encoding="utf-8", errors="replace") as f:
            counters = parse(f)
        if counters.samples == 0:
            raise ValueError("no server link payload stats; this log does NOT prove zero traffic")
        print(json.dumps(counters.summary(duration_seconds=args.measured_duration_sec),
                         indent=2, sort_keys=True))
    except (ValueError, OSError) as error:
        print(f"SHYT_RELAY_MEASUREMENT_REJECTED: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
